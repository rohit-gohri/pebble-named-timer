    '          startImmediately: t.id === 0 ? !!t.startImmediately : false',
    '        };',
    '      }),',
    '      presets: presets.map(function(p) {',
    '        return (p || "").trim().slice(0, MAX_NAME_LEN);',
    '      })',
    '    };',
    '    document.location = getReturnTo() + encodeURIComponent(JSON.stringify(payload));',
    '  });',
    '',
    '  renderStatus();',
